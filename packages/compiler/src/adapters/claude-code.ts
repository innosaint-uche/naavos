import type { AvatarPackage, Rule } from '@naavos/schema';

import type { FileMap } from '../index.js';

/**
 * Claude Code adapter — generates CLAUDE.md with the avatar's identity,
 * communication style, operating rules, and privacy settings.
 */
export function claudeCodeAdapter(pkg: AvatarPackage): FileMap {
  const identity = pkg.identity ?? {};
  const communication = pkg.communication ?? {};
  const rules = pkg.operating_rules ?? [];

  const content = `# CLAUDE.md — NAAvOS Integration

> Generated by NAAvOS. Do not edit manually — recompile instead.

## Who I Am

**${identity.name || 'User'}**

${identity.self_description || 'No description provided.'}

## How I Work

### Communication Style
- **Tone:** ${communication.tone || 'Direct, authoritative, straight-talk'}
- **Structure:** ${communication.structure || 'Bulleted, action-oriented'}
- **Verbosity:** ${communication.verbosity || 'Minimal — no preamble, no fluff'}

${communication.prohibited_patterns && communication.prohibited_patterns.length > 0 ? `### Patterns to Avoid\n${communication.prohibited_patterns.map((p) => `- ${p}`).join('\n')}\n` : ''}

## Operating Rules

${formatRules(rules)}

## Privacy

- **Cloud sync:** ${fmtBool(pkg.privacy?.consents?.['allow-cloud-sync'])}
- **Telemetry:** ${fmtBool(pkg.privacy?.consents?.['allow-telemetry'])}

---
*Compiled from NAAvOS package ${pkg.metadata?.package_id || 'unknown'} — ${new Date().toISOString()}*
`;

  return new Map([['CLAUDE.md', content]]);
}

function formatRules(rules: Rule[]): string {
  return rules
    .map((r, i) => `${i + 1}. **${r.id || r.statement.slice(0, 30)}** — ${r.statement}`)
    .join('\n');
}

function fmtBool(value: boolean | undefined): 'Allowed' | 'Disabled' {
  return value ? 'Allowed' : 'Disabled';
}
